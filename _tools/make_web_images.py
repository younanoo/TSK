#!/usr/bin/env python3
"""Prepare images for the site.  Run from the site folder:   python _tools/make_web_images.py
- Reads every image in img/ (chapter pictures: img/Gen1.jpg, img/Psa23.png ...)
  and in img/books/ (book covers: img/books/GenAll.png, img/books/ExoAll.jpg ...)
- Writes web-sized copies to img/web/NAME-800 / NAME-1600 (.webp and .jpg)
- Writes assets/imgs.js: the list of prepared images, so pages load the small copies
Chapter images are named by book abbreviation + chapter number: Gen1, Exo20, 1Sa17, Psa23 ...
Needs Pillow:  pip install pillow"""
import os, sys, json
from PIL import Image
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC, WEB = os.path.join(ROOT, "img"), os.path.join(ROOT, "img", "web")
os.makedirs(WEB, exist_ok=True)
made, manifest = 0, {}
import re
files = [os.path.join(SRC, f) for f in sorted(os.listdir(SRC))]
COVERS = set()
for d in ("books", "book"):
    D = os.path.join(SRC, d)
    if os.path.isdir(D):
        for f in sorted(os.listdir(D)): files.append(os.path.join(D, f)); COVERS.add(os.path.join(D, f))
for p in files:
    f = os.path.basename(p)
    if not os.path.isfile(p): continue
    stem = os.path.splitext(f)[0] if os.path.splitext(f)[1].lower() in (".jpg", ".jpeg", ".png", ".webp") else f
    if p in COVERS: stem = re.sub(r"(?i)all$", "All", stem)     # ExoAll / Exoall / EXOALL -> ExoAll
    try: im = Image.open(p); W, H = im.size
    except Exception: continue
    rgb = None
    for w in (1600, 800):
        ww = min(w, W); hh = round(H * ww / W)
        outs = [os.path.join(WEB, f"{stem}-{w}.{e}") for e in ("webp", "jpg")]
        if all(os.path.exists(o) and os.path.getmtime(o) >= os.path.getmtime(p) for o in outs): continue
        if rgb is None: rgb = im.convert("RGB")
        r = rgb.resize((ww, hh), Image.LANCZOS)
        r.save(outs[0], quality=80, method=6); r.save(outs[1], quality=82, optimize=True, progressive=True); made += 1
    w16 = min(1600, W); manifest[stem] = [w16, round(H * w16 / W)]
open(os.path.join(ROOT, "assets", "imgs.js"), "w", encoding="utf-8").write(
    "/* generated by _tools/make_web_images.py — do not edit */\nwindow.IMGS=" + json.dumps(manifest, separators=(",", ":")) + ";\n")
print(f"{len(manifest)} images listed, {made} sizes written")
